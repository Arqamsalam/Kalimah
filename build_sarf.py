#!/usr/bin/env python3
"""
Builds data/sarf.js — the ṣarf ṣaghīr (past, present, maṣdar, doer, passive,
done-to, command, prohibition, place/time, instrument) for every verb the site
shows, from sarf.json.

sarf.json is hand-checked: each row was written out in full, then the verbal
forms were cross-checked against an independent conjugator (Qutrub) and the
participles against their patterns. Edit sarf.json, then run:

    python3 build_sarf.py

Rows are keyed "root|form", e.g. "نصر|1" — the same root (no spaces) and verb
form that data/morph.js gives each word, so the site can find a word's table.
"""
import json, os

HERE   = os.path.dirname(os.path.abspath(__file__))
SRC    = os.path.join(HERE, "sarf.json")
OUT    = os.path.join(HERE, "data", "sarf.js")
FIELDS = ["past", "present", "masdar", "fail", "pastPassive", "presentPassive",
          "maful", "amr", "nahy", "zarf", "ala", "trans", "bab", "en", "note"]

rows  = json.load(open(SRC, encoding="utf-8"))
table = {}
for r in rows:
    root, form = r["key"].split("|")[:2]
    table[root + "|" + form] = [r[f] for f in FIELDS]

with open(OUT, "w", encoding="utf-8") as f:
    f.write("/* Generated by build_sarf.py from sarf.json — do not edit by hand.\n"
            "   The ṣarf ṣaghīr of every verb on the site, keyed \"root|form\".  */\n")
    f.write("const SARF_FIELDS = " + json.dumps(FIELDS) + ";\n")
    f.write("const SARF = " + json.dumps(table, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(f"data/sarf.js: {len(table)} verbs")
